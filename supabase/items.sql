create or replace function public.admin_confirm_turnover(p_item_id text)
returns public.items
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_item public.items;
begin
  if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' then
    raise exception 'Admin access required';
  end if;

  update public.items
  set custody_status = 'in_custody',
      turnover_confirmed_at = now(),
      turnover_confirmed_by = auth.uid()
  where id = p_item_id
    and status = 'found'
    and custody_status = 'pending_turnover'
  returning * into updated_item;

  if updated_item.id is null then
    raise exception 'This found item is not awaiting turnover';
  end if;

  insert into public.item_events (item_id, action, actor_id)
  values (p_item_id, 'turnover_confirmed', auth.uid());
  return updated_item;
end;
$$;

create or replace function public.admin_review_claim(
  p_claim_id uuid,
  p_decision text,
  p_review_note text default null,
  p_collection_point text default null
)
returns public.claims
language plpgsql
security definer
set search_path = public
as $$
declare
  current_claim public.claims;
  updated_claim public.claims;
begin
  if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' then
    raise exception 'Admin access required';
  end if;
  if p_decision not in ('approved', 'rejected') then
    raise exception 'Invalid claim decision';
  end if;

  select * into current_claim
  from public.claims
  where id = p_claim_id
  for update;

  if current_claim.id is null or current_claim.status <> 'pending_review' then
    raise exception 'This claim is no longer pending review';
  end if;
  if current_claim.claimant_id = auth.uid() then
    raise exception 'An admin cannot approve their own claim';
  end if;
  if p_decision = 'approved' and not exists (
    select 1 from public.items
    where id = current_claim.item_id and custody_status = 'in_custody'
  ) then
    raise exception 'This item is no longer available for approval';
  end if;
  if p_decision = 'approved' and exists (
    select 1 from public.claims
    where item_id = current_claim.item_id and status = 'approved' and id <> p_claim_id
  ) then
    raise exception 'Another claim is already approved for this item';
  end if;

  update public.claims
  set status = p_decision,
      review_note = nullif(trim(p_review_note), ''),
      collection_point = case when p_decision = 'approved' then nullif(trim(p_collection_point), '') else null end,
      reviewed_at = now(),
      reviewed_by = auth.uid()
  where id = p_claim_id
  returning * into updated_claim;

  insert into public.item_events (item_id, claim_id, action, actor_id, metadata)
  values (
    current_claim.item_id,
    p_claim_id,
    case when p_decision = 'approved' then 'claim_approved' else 'claim_rejected' end,
    auth.uid(),
    jsonb_build_object('review_note', updated_claim.review_note)
  );
  return updated_claim;
end;
$$;

create or replace function public.admin_release_claim(
  p_claim_id uuid,
  p_verified_student_id text
)
returns public.claims
language plpgsql
security definer
set search_path = public
as $$
declare
  current_claim public.claims;
  current_item public.items;
  claimant_student_id text;
  updated_claim public.claims;
begin
  if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' then
    raise exception 'Admin access required';
  end if;

  select * into current_claim from public.claims where id = p_claim_id for update;
  if current_claim.id is null or current_claim.status <> 'approved' or current_claim.released_at is not null then
    raise exception 'This claim is not available for release';
  end if;

  select * into current_item from public.items where id = current_claim.item_id for update;
  if current_item.custody_status <> 'in_custody' or current_item.claimed_at is not null then
    raise exception 'This item has already been released or is not in custody';
  end if;

  select raw_user_meta_data ->> 'student_id' into claimant_student_id
  from auth.users
  where id = current_claim.claimant_id;
  if claimant_student_id is null or claimant_student_id <> trim(p_verified_student_id) then
    raise exception 'The school ID does not match the claimant';
  end if;

  update public.claims
  set released_at = now(), released_by = auth.uid()
  where id = p_claim_id
  returning * into updated_claim;

  update public.items
  set custody_status = 'claimed',
      claimed_at = now(),
      claimed_by = current_claim.claimant_id
  where id = current_claim.item_id;

  insert into public.item_events (item_id, claim_id, action, actor_id)
  values (current_claim.item_id, p_claim_id, 'item_released', auth.uid());
  return updated_claim;
end;
$$;

