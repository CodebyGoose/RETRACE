create policy "Students can submit claims"
on public.claims for insert
to authenticated
with check (
  claimant_id = auth.uid()
  and status = 'pending_review'
  and exists (
    select 1 from public.public_item_details
    where public_item_details.id = claims.item_id
      and public_item_details.status = 'found'
      and public_item_details.custody_status = 'in_custody'
  )
);

drop policy if exists "Students can view their own events" on public.item_events;
create policy "Students can view their own events"
on public.item_events for select
to authenticated
using (
  actor_id = auth.uid()
  or exists (
    select 1 from public.claims
    where claims.id = item_events.claim_id
      and claims.claimant_id = auth.uid()
  )
);

