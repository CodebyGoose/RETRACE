create table if not exists public.items (
  id text primary key,
  name text not null,
  status text not null check (status in ('found', 'lost')),
  category text not null,
  place text not null,
  detail_place text,
  date date not null default current_date,
  time text,
  image text,
  hero_image text,
  description text,
  collection_point text,
  hours text,
  reported_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  custody_status text,
  turnover_confirmed_at timestamptz,
  turnover_confirmed_by uuid references auth.users(id),
  claimed_at timestamptz,
  claimed_by uuid references auth.users(id)
);

alter table public.items add column if not exists reported_by uuid references auth.users(id);
alter table public.items add column if not exists custody_status text;
alter table public.items add column if not exists turnover_confirmed_at timestamptz;
alter table public.items add column if not exists turnover_confirmed_by uuid references auth.users(id);
alter table public.items add column if not exists claimed_at timestamptz;
alter table public.items add column if not exists claimed_by uuid references auth.users(id);

update public.items
set custody_status = case when status = 'found' then 'pending_turnover' else null end
where custody_status is null;

alter table public.items drop constraint if exists items_custody_status_check;
alter table public.items add constraint items_custody_status_check check (
  (status = 'found' and custody_status in ('pending_turnover', 'in_custody', 'claimed'))
  or (status = 'lost' and custody_status is null)
);

create table if not exists public.claims (
  id uuid primary key default gen_random_uuid(),
  item_id text not null references public.items(id) on delete cascade,
  claimant_id uuid not null references auth.users(id) on delete cascade,
  lost_place text not null,
  lost_date date not null,
  lost_time text not null,
  identifying_details text not null,
  evidence_path text,
  status text not null default 'pending_review' check (status in ('pending_review', 'approved', 'rejected')),
  review_note text,
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id),
  collection_point text,
  released_at timestamptz,
  released_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create unique index if not exists one_active_claim_per_student_item
on public.claims (item_id, claimant_id)
where status in ('pending_review', 'approved');

create unique index if not exists one_approved_claim_per_item
on public.claims (item_id)
where status = 'approved';

create table if not exists public.item_events (
  id bigint generated by default as identity primary key,
  item_id text not null references public.items(id) on delete cascade,
  claim_id uuid references public.claims(id) on delete set null,
  action text not null check (action in ('turnover_confirmed', 'claim_submitted', 'claim_approved', 'claim_rejected', 'item_released')),
  actor_id uuid not null references auth.users(id),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.record_claim_submission()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.item_events (item_id, claim_id, action, actor_id)
  values (new.item_id, new.id, 'claim_submitted', new.claimant_id);
  return new;
end;
$$;

drop trigger if exists claims_submission_event on public.claims;
create trigger claims_submission_event
after insert on public.claims
for each row execute function public.record_claim_submission();

create or replace view public.public_item_details
with (security_invoker = true) as
select
  id, name, status, category, place, detail_place, date, time, image, hero_image,
  description, collection_point, hours, created_at, custody_status,
  turnover_confirmed_at, claimed_at
from public.items
where status = 'lost' or custody_status in ('pending_turnover', 'in_custody', 'claimed');

